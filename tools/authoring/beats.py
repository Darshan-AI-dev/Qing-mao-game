# ---- validation ------------------------------------------------------------
def main():
    covered = {}
    ids = set()
    all_sets = set()
    for x in BEATS:
        assert x.id not in ids, f'duplicate beat id {x.id}'
        ids.add(x.id)
        all_sets |= set(x.sets)
        for c in range(x.ch[0], x.ch[1] + 1):
            assert c not in covered, f'chapter {c} covered twice: {covered.get(c)} and {x.id}'
            covered[c] = x.id
    missing = [c for c in range(1, 201) if c not in covered]
    assert not missing, f'chapters with no beat: {missing}'
    for x in BEATS:
        for r in x.requires:
            assert r in ids, f'{x.id} requires unknown beat {r}'
    evidence_ids = {e for x in BEATS for e in x.evidence}
    for x in BEATS:
        for r in x.reads:
            assert r in all_sets or r in evidence_ids, f'{x.id} reads unset flag {r}'

    by_act = collections.defaultdict(list)
    for x in BEATS:
        by_act[x.act].append({
            'id': x.id,
            'title': x.title,
            'chapters': list(x.ch),
            'coverage': x.cov,
            'template': x.template,
            'area': x.area,
            'script': f'{x.act}/{x.ch[0]:03d}-{x.id.split(".", 1)[1].replace(".", "-")}.json',
            'requires': list(x.requires),
            'sets': list(x.sets),
            'reads': list(x.reads),
            'evidence': list(x.evidence),
            'cast': list(x.cast),
            'mustLand': x.must,
            'recollection': x.recollection,
            'foresight': x.foresight,
            'art': x.art,
            'sfx': None,
            'music': None,
            'day': x.day,
            'weather': x.weather,
            'legacyStep': legacy_step(x.ch[1]),
            'designNote': x.note,
        })

    root = pathlib.Path('content/qingmao/acts')
    for act, beats in by_act.items():
        p = root / act / 'beats.json'
        p.write_text(json.dumps({
            'act': act,
            'note': 'Beats are addressed by stable ID. legacyStep maps a pre-v5 save\'s step counter onto this graph; inserting a beat never renumbers another.',
            'beats': beats,
        }, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
        print(f'{p}: {len(beats)} beats, chapters {beats[0]["chapters"][0]}-{beats[-1]["chapters"][1]}')
    print(f'total {len(BEATS)} beats, 200/200 chapters covered')
    cov = collections.Counter(x.cov for x in BEATS)
    print('beat coverage levels:', dict(cov))
    chcov = collections.Counter(next(x.cov for x in BEATS if x.id == covered[c]) for c in range(1, 201))
    print('chapter coverage levels:', dict(chcov))
    print('must-land beats:', sorted({x.must for x in BEATS if x.must}))

main()
