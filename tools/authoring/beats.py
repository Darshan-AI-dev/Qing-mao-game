# Legacy step anchors from the previous build's save format (v4, 76 stages):
# steps 0-8 -> ch 1-50, 8-24 -> 51-100, 24-44 -> 101-150, 44-76 -> 151-200.
ANCHORS = [(1, 50, 0, 8), (51, 100, 8, 24), (101, 150, 24, 44), (151, 200, 44, 76)]

def legacy_step(last_chapter):
    for c0, c1, s0, s1 in ANCHORS:
        if c0 <= last_chapter <= c1:
            t = (last_chapter - c0 + 1) / (c1 - c0 + 1)
            return round(s0 + t * (s1 - s0))
    raise ValueError(last_chapter)

B = collections.namedtuple('B', 'id act ch cov title template area must sets requires reads evidence recollection foresight art day weather cast note', defaults=(None,)*8 + ((), (), (), (), None, None, None, 1, 'clear', (), None))

def b(id, act, ch, cov, title, template, area, must=None, sets=(), requires=(), reads=(),
      evidence=(), recollection=None, foresight=None, art=None, day=1, weather='clear', cast=(), note=None):
    return B(id, act, ch, cov, title, template, area, must, sets, requires, reads, evidence,
             recollection, foresight, art, day, weather, cast, note)

